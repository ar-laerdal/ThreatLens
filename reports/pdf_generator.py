"""PDF threat model report (ReportLab). All narrative text is generated deterministically from the
validated data; every model-supplied string is XML-escaped before it reaches a Paragraph.
"""
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from core import risk_engine
from core.schemas import ThreatModel

SEV_COLORS = {k: colors.HexColor(v) for k, v in risk_engine.SEVERITY_COLORS.items()}
NAVY = colors.HexColor("#0B1220")
ACCENT = colors.HexColor("#00A383")

DISCLAIMER = (
    "This report was generated by an AI agent from the supplied architecture material. Findings are "
    "unverified hypotheses until reviewed by a qualified security engineer. Recommended controls are not "
    "evidence that any control is implemented. Security test cases must only be run with authorisation, in "
    "non-production environments."
)


def _styles():
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle("t", parent=base["Title"], textColor=NAVY, fontSize=24, alignment=TA_LEFT),
        "h1": ParagraphStyle("h1", parent=base["Heading1"], textColor=NAVY, fontSize=16, spaceBefore=14, spaceAfter=6),
        "h2": ParagraphStyle("h2", parent=base["Heading2"], textColor=ACCENT, fontSize=12, spaceBefore=8, spaceAfter=3),
        "body": ParagraphStyle("b", parent=base["BodyText"], fontSize=9.5, leading=13),
        "cell": ParagraphStyle("c", parent=base["BodyText"], fontSize=8, leading=10),
        "cellb": ParagraphStyle("cb", parent=base["BodyText"], fontSize=8, leading=10, textColor=colors.white),
        "warn": ParagraphStyle("w", parent=base["BodyText"], fontSize=9, leading=12, textColor=colors.HexColor("#7A4B00"),
                               backColor=colors.HexColor("#FFF4D6"), borderPadding=6),
    }


def _p(text, style) -> Paragraph:
    return Paragraph(escape(str(text)).replace("\n", "<br/>"), style)


def _bullets(items, style) -> Paragraph:
    return Paragraph("<br/>".join(f"&bull; {escape(str(i))}" for i in items) or "-", style)


def _table(headers, rows, widths, st) -> Table:
    data = [[_p(h, st["cellb"]) for h in headers]]
    data += [[c if isinstance(c, Paragraph) else _p(c, st["cell"]) for c in row] for row in rows]
    table = Table(data, colWidths=[w * mm for w in widths], repeatRows=1)
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), NAVY),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#B8C0CC")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F3F5F8")]),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    return table


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(colors.HexColor("#6B7280"))
    canvas.drawString(18 * mm, 10 * mm, "AI-generated threat model - requires human review")
    canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _severity_cell(sev: str, st) -> Paragraph:
    hex_color = risk_engine.SEVERITY_COLORS[sev]
    return Paragraph(f'<font color="{hex_color}"><b>{sev}</b></font>', st["cell"])


def executive_summary(model: ThreatModel) -> str:
    counts = risk_engine.severity_counts(model.threats)
    top = model.threats[:3]
    text = (
        f"The AI agent analysed '{model.source_filename}' for {model.project_name}, identifying "
        f"{len(model.architecture.components)} components and {len(model.architecture.data_flows)} data flows. "
        f"It proposed {len(model.threats)} STRIDE threats: {counts['Critical']} critical, {counts['High']} high, "
        f"{counts['Medium']} medium and {counts['Low']} low, with {len(model.abuse_cases)} abuse cases, "
        f"{len(model.controls)} control recommendations and {len(model.test_cases)} security test cases."
    )
    if top:
        text += " Highest-ranked threats: " + "; ".join(f"{t.id} {t.title} ({t.severity})" for t in top) + "."
    reviewed = sum(t.review_status != "Unreviewed" for t in model.threats)
    text += f" Human review status: {reviewed} of {len(model.threats)} threats reviewed."
    return text


def build_pdf(model: ThreatModel) -> bytes:
    st = _styles()
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=18 * mm,
        title=f"Threat Model - {model.project_name}", author="ThreatLens",
    )
    arch = model.architecture
    s: list = []

    # --- cover + executive summary
    s += [Spacer(1, 30 * mm), _p("Threat Modeling Report", st["title"]), _p(model.project_name, st["h2"]), Spacer(1, 6)]
    s += [_p(f"Source: {model.source_filename}  |  Generated: {model.generated_at}  |  Model: {model.llm_model or 'n/a'}", st["body"])]
    s += [Spacer(1, 10), _p(DISCLAIMER, st["warn"]), Spacer(1, 8)]
    s += [_p("1. Executive Summary", st["h1"]), _p(executive_summary(model), st["body"])]
    if model.warnings:
        s += [_p("Pipeline warnings", st["h2"]), _bullets(model.warnings, st["body"])]
    s += [_p("Risk methodology", st["h2"]), _p(risk_engine.METHODOLOGY, st["body"]), PageBreak()]

    # --- architecture overview / components / flows
    s += [_p("2. Architecture Overview", st["h1"]), _p(arch.summary or "No summary extracted.", st["body"])]
    if arch.trust_boundaries:
        s += [_p("Trust boundaries", st["h2"]),
              _bullets([f"{b.name}: {b.description}" for b in arch.trust_boundaries], st["body"])]
    if arch.sensitive_assets:
        s += [_p("Sensitive assets", st["h2"]),
              _bullets([f"{a.name} (sensitivity: {a.sensitivity}) {a.location}" for a in arch.sensitive_assets], st["body"])]
    if arch.assumptions:
        s += [_p("AI assumptions (not confirmed by the source)", st["h2"]), _bullets(arch.assumptions, st["body"])]
    if arch.open_questions:
        s += [_p("Open questions for the design team", st["h2"]), _bullets(arch.open_questions, st["body"])]

    s += [_p("3. Identified Components", st["h1"])]
    s += [_table(
        ["Name", "Type", "Boundary", "Description", "Basis / review"],
        [[c.name, c.type, c.trust_boundary, c.description,
          f"{c.basis}{' - NEEDS REVIEW: ' + c.review_reason if c.needs_review else ''}"] for c in arch.components],
        [30, 26, 20, 62, 36], st)]

    s += [_p("4. Data Flow Analysis", st["h1"])]
    s += [_table(
        ["Source", "Destination", "Data", "Protocol", "Auth", "Crosses boundary", "Basis / review"],
        [[f.source, f.destination, f.data, f.protocol,
          {True: "Yes", False: "No", None: "Unknown"}[f.authenticated], "Yes" if f.crosses_trust_boundary else "No",
          f"{f.basis}{' - NEEDS REVIEW' if f.needs_review else ''}"] for f in arch.data_flows],
        [24, 24, 34, 20, 14, 18, 36], st)]
    s.append(PageBreak())

    # --- threats
    s += [_p("5. Threat Assessment (STRIDE)", st["h1"])]
    s += [_table(
        ["ID", "Threat", "Component", "STRIDE", "L", "I", "Score", "Severity", "Review"],
        [[t.id, t.title, t.affected_component, t.stride_category, t.likelihood, t.impact, t.risk_score,
          _severity_cell(t.severity, st), t.review_status] for t in model.threats],
        [12, 46, 28, 26, 7, 7, 11, 16, 21], st)]
    for t in model.threats:
        s += [_p(f"{t.id} - {t.title}", st["h2"])]
        s += [_table(
            ["Field", "Detail"],
            [["Description", t.description], ["Attack scenario", t.attack_scenario],
             ["Potential impact", t.potential_impact],
             ["Likelihood / impact", f"{t.likelihood} ({risk_engine.LIKELIHOOD_LABELS[t.likelihood]}) / "
                                     f"{t.impact} ({risk_engine.IMPACT_LABELS[t.impact]})"],
             ["Evidence", t.evidence or "None provided"],
             ["Confidence", t.confidence + ("" if t.grounded else " (component not found in architecture)")]],
            [30, 144], st)]
    s.append(PageBreak())

    # --- abuse cases
    s += [_p("6. Abuse Cases", st["h1"])]
    for a in model.abuse_cases:
        s += [_p(f"{a.id} - {a.title}", st["h2"])]
        s += [_table(
            ["Field", "Detail"],
            [["Attacker profile", a.attacker_profile], ["Target component", a.target_component],
             ["Preconditions", _bullets(a.preconditions, st["cell"])], ["Scenario", a.scenario],
             ["Security impact", a.security_impact],
             ["Prevention", _bullets(a.prevention_measures, st["cell"])],
             ["Related threats", ", ".join(a.related_threat_ids) or "-"]],
            [30, 144], st)]

    # --- controls + mitigations
    s += [PageBreak(), _p("7. Security Control Mapping", st["h1"]),
          _p("All controls below are recommendations. None are assumed to be implemented.", st["body"])]
    s += [_table(
        ["Threat", "Control", "Why relevant", "Framework references", "Priority"],
        [[c.threat_id, c.control, c.relevance,
          _bullets([f"{r.framework}: {r.reference}" for r in c.framework_refs], st["cell"]), c.priority]
         for c in model.controls],
        [14, 34, 52, 52, 22], st)]

    s += [_p("8. Recommended Mitigations", st["h1"])]
    s += [_table(
        ["Threat", "Control", "Implementation recommendation", "Priority"],
        [[c.threat_id, c.control, c.implementation, c.priority] for c in model.controls],
        [14, 36, 102, 22], st)]
    s.append(PageBreak())

    # --- tests
    s += [_p("9. Security Test Cases", st["h1"]),
          _p("For authorised validation in non-production environments only. The agent never executes these tests.",
             st["warn"])]
    for tc in model.test_cases:
        s += [_p(f"{tc.id} (threat {tc.threat_id}) - {tc.component}", st["h2"])]
        s += [_table(
            ["Field", "Detail"],
            [["Objective", tc.objective], ["Preconditions", _bullets(tc.preconditions, st["cell"])],
             ["Procedure", _bullets([f"{i}. {x}" for i, x in enumerate(tc.procedure, 1)], st["cell"])],
             ["Expected secure behavior", tc.expected_secure_behavior], ["Pass criteria", tc.pass_criteria],
             ["Fail criteria", tc.fail_criteria]],
            [34, 140], st)]

    # --- overall recommendations
    s += [PageBreak(), _p("10. Overall Security Recommendations", st["h1"])]
    top_controls = [c for c in model.controls if c.priority in ("Critical", "High")]
    s += [_p("Priority actions", st["h2"]),
          _bullets([f"{c.threat_id}: {c.control}" for c in top_controls[:12]] or ["No critical/high priority controls."],
                   st["body"])]
    s += [_p("Process recommendations", st["h2"]), _bullets([
        "Have a security engineer confirm or reject each threat before treating it as a finding.",
        "Resolve the architecture items flagged for review and the open questions above, then re-run the analysis.",
        "Verify which recommended controls already exist; this report does not assess implementation.",
        "Run the security test cases in an authorised non-production environment and record results.",
        "Re-run the threat model whenever the architecture changes.",
    ], st["body"])]

    doc.build(s, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()
